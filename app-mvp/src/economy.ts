// Економіка коїнів. Єдиний множник для ВСІХ джерел нарахування (урок, квіз, симулятори, щоденні завдання).
// 0.5 = коїни нараховуються вдвічі повільніше (рішення автора 2026-10-27). Ціни в магазині (shop.ts) не змінюються,
// наявні баланси гравців не чіпаємо.
export const COIN_RATE = 0.5;

export const scaleCoins = (n: number): number => Math.round(n * COIN_RATE);
