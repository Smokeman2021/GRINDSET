// Сумісність з назвами у зносках уроків: [→ Бібліотека: X]
export function categoryFor(label: string): string | undefined {
  const l = label.toLowerCase();
  return CATEGORIES.find((c) => c.id.toLowerCase() === l || l.includes(c.id.toLowerCase()) || c.id.toLowerCase().includes(l))?.id;
}
