export type Step =
  | {
      type: 'teach';
      title: string;
      body: string;
      example?: string;
    }
  | {
      type: 'choice';
      layer: 1 | 2;
      q: string;
      scenario?: string;
      options: string[];
      answer: number;
      okMsg: string;
      noMsg: string;
      explain?: string;
    }
  | {
      type: 'fill';
      layer: 1 | 2;
      q: string;
      before: string;
      after: string;
      options: string[];
      answer: number;
      okMsg: string;
      noMsg: string;
      explain?: string;
    };

export type Lesson = {
  id: string;
  code: string;
  title: string;
  minutes: number;
  steps: Step[];
  kind?: 'checkpoint' | 'quiz';
  passThreshold?: number; // 0-1, потрібна точність аби пройти (тільки checkpoint)
  requires?: string[]; // id уроків, які мають бути пройдені, щоб відкрити (квізи)
};

