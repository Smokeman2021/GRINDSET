// Список заявок кабінету за 3 дні: 30 рядків, два не дійшли до CRM (контрольна й повторна відправка)
export type LeadRow = { t: string; name: string; phone: string; crm: boolean; extra?: 'control' | 'resubmit' };
const NAMES = ['Олена', 'Андрій', 'Ірина', 'Богдан', 'Марія', 'Олег', 'Наталя', 'Віктор', 'Світлана', 'Тарас'];
export const LEAD_MARKS = { control: 'Контрольна', resubmit: 'Повторна відправка' } as const;
export const LEADS: LeadRow[] = (() => {
  const rows: LeadRow[] = [];
  for (let i = 0; i < 28; i++) {
    const day = 1 + Math.floor(i / 10);
    // час іде по порядку в межах дня: 09:00…19:54
    const mins = 9 * 60 + (i % 10) * 70 + ((i * 13) % 25);
    const h = Math.floor(mins / 60);
    const m = mins % 60;
    rows.push({ t: `д${day} ${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`, name: NAMES[i % NAMES.length], phone: `+380 •• ••• •${String(10 + ((i * 37) % 90)).padStart(2, '0')}`, crm: true });
  }
  // контрольна заявка напарника перед запуском — на самому початку
  rows.unshift({ t: 'д1 08:55', name: 'Тест', phone: '+380 •• ••• •00', crm: false, extra: 'control' });
  // повторна відправка з того ж номера через хвилину після 12-ї заявки
  const src = rows[12];
  const [d, hm] = src.t.split(' ');
  const [hh, mm] = hm.split(':').map(Number);
  const t2 = `${d} ${String(hh + (mm === 59 ? 1 : 0)).padStart(2, '0')}:${String((mm + 1) % 60).padStart(2, '0')}`;
  rows.splice(13, 0, { t: t2, name: src.name, phone: src.phone, crm: false, extra: 'resubmit' });
  return rows;
})();

