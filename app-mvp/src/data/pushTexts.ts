const fill = (s: string, n: number, name: string) => s.split('{n}').join(String(n)).split('{name}').join(name || 'Гравець');

export function pickPush(kind: PushKind, seed: number, n: number, name: string) {
  const list = PUSH_TEXTS[kind];
  const t = list[Math.abs(seed) % list.length];
  return { title: fill(t.title, n, name), body: fill(t.body, n, name) };
}
