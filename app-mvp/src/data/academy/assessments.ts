import { brief, choice, numeric, type BStep } from '../branch.ts';
import type { AcademyTrack, VerticalCode } from '../academyIds.ts';
import type { FinalPart } from '../branchRules.ts';

type Answers = [string, string, string];
const pick = (q: string, options: Answers, explain: string, extra: Pick<BStep, 'see' | 'part' | 'blockLaunch'> = {}) =>
  choice(q, options, 0, explain, extra);
const value = (q: string, answer: number, currency: string, explain: string, see: string, part?: FinalPart) =>
  numeric(q, [{ label: 'Результат', answer, unit: currency }], explain, { see, part });

export type Assessment = { diagnostic: BStep[]; practice?: BStep[]; final?: BStep[] };

function vertical(
  track: VerticalCode,
  diagnostic: [BStep, BStep],
  practice: BStep,
  scenario: string,
  decision: [string, Answers, string],
  math: [string, number, string, string],
  next: [string, Answers, string],
  regulated = false,
): Assessment {
  const id = `BR-${track}-A1`;
  return {
    diagnostic,
    practice: [practice],
    final: [
      brief('Самостійний кейс · навчальні дані', scenario),
      pick(...decision, { part: 'decision', see: `${id}-L10`, ...(regulated ? { blockLaunch: [1] } : {}) }),
      value(...math, `${id}-L08`, 'data'),
      pick(...next, { part: 'next', see: `${id}-L09` }),
    ],
  };
}

