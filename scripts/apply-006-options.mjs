let changed = 0;
const files = new Map();
const get = (f) => {
  if (!files.has(f)) {
    const raw = fs.readFileSync(path.join(ROOT, f), 'utf8');
    files.set(f, { raw, s: raw.split('\r\n').join('\n'), crlf: raw.includes('\r\n') });
  }
  return files.get(f);
};
const quote = (f, t, literal) => (literal ? t : f.endsWith('.json') ? null : `'${t}'`);
for (const [f, from, to, times = 1, literal = false] of EDITS) {
  const file = get(f);
  // рядок у лапках (TS) або вже з лапками (JSON / literal); для TS без лапок, якщо він містить лапки сам
  const a = f.endsWith('.json') || literal || from.includes("'") ? from : quote(f, from, false);
  const b = f.endsWith('.json') || literal || from.includes("'") ? to : quote(f, to, false);
  const n = file.s.split(a).length - 1;
  if (n === 0 && file.s.includes(b)) continue; // уже застосовано
  if (n !== times) throw new Error(`${f}: «${from.slice(0, 60)}» знайдено ${n} раз(и), очікувалось ${times}`);
  file.s = file.s.split(a).join(b);
  changed++;
}
for (const [f, file] of files) {
  const out = file.crlf ? file.s.split('\n').join('\r\n') : file.s;
  if (out !== file.raw) fs.writeFileSync(path.join(ROOT, f), out);
  if (f.endsWith('.json')) JSON.parse(out);
}
console.log(`правок застосовано: ${changed} з ${EDITS.length}`);
